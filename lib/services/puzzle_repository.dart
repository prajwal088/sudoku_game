import 'dart:isolate';
import 'dart:math';
import 'dart:typed_data';

/// ============================================================================
/// PuzzleRepository
/// ----------------------------------------------------------------------------
/// Provides deterministic Sudoku puzzles for global level IDs.
///
/// Responsibilities:
/// - Generate a deterministic Sudoku puzzle for each global level.
/// - Generate a valid complete Sudoku solution.
/// - Remove clues while preserving exactly one solution.
/// - Cache generated puzzles in memory.
/// - Return defensive copies to callers.
/// - Keep puzzle-generation rules independent from gameplay progression.
///
/// Architecture:
/// - The global level number is the puzzle identifier.
/// - ProgressService owns progression state and is the progression SOT.
/// - WorldManager owns world/batch calculations.
/// - SudokuGenerator may be used independently for raw Sudoku generation.
/// - This repository owns puzzle identity, difficulty and uniqueness.
///
/// Difficulty:
/// - Levels   1-25  -> Easy
/// - Levels  26-75  -> Medium
/// - Levels  76-150 -> Hard
/// - Levels 151+    -> Expert
///
/// Empty cells:
/// - Easy   -> 35
/// - Medium -> 45
/// - Hard   -> 55
/// - Expert -> 57
///
/// IMPORTANT:
/// - Level numbers are 1-based.
/// - Every accepted puzzle has exactly one solution.
/// - The same level produces the same puzzle across application launches.
/// - The repository does NOT track completion, stars, unlocks or progress.
///
/// DETERMINISM CONTRACT:
/// The puzzle for a level is a pure function of (level, attempt) through a
/// seeded [Random]. The order of random calls (board fill shuffles, then the
/// clue-removal shuffle), the cell-selection rule (fewest candidates, first
/// in row-major order) and the seeds below MUST NOT change, or every level's
/// puzzle changes. Speed-ups must keep those exactly the same.
///
/// Performance:
/// Generation is CPU-heavy. [getPuzzleForLevel] / [getPuzzle] run on the
/// calling isolate; prefer [getPuzzleAsync] / [getPuzzleForLevelAsync] from UI
/// code so generation runs on a background isolate.
/// ============================================================================

class PuzzleRepository {
  // ==========================================================================
  // INSTANCES
  // ==========================================================================

  static final PuzzleRepository _shared = PuzzleRepository.isolated();

  /// Returns the shared repository.
  ///
  /// All callers share one cache, so a level generated by one service is not
  /// generated again by another (for example each `LevelService` instance).
  factory PuzzleRepository() => _shared;

  /// Creates an independent repository with its own empty cache.
  ///
  /// Intended for tests.
  PuzzleRepository.isolated();

  // ==========================================================================
  // CACHE
  // ==========================================================================

  final Map<int, _PuzzleData> _cache = <int, _PuzzleData>{};

  /// Background generations currently in flight, so concurrent requests for
  /// the same level share one isolate run.
  final Map<int, Future<_PuzzleData>> _pending = <int, Future<_PuzzleData>>{};

  // ==========================================================================
  // PUBLIC API
  // ==========================================================================

  /// Returns the deterministic puzzle for [levelNumber].
  ///
  /// The same level number produces the same puzzle across application
  /// launches.
  ///
  /// Returns null when [levelNumber] is less than 1.
  ///
  /// A defensive copy is always returned.
  ///
  /// Generates synchronously on a cache miss; see [getPuzzleForLevelAsync].
  Map<String, dynamic>? getPuzzleForLevel(int levelNumber) {
    if (levelNumber < _minimumLevel) {
      return null;
    }

    return _getOrGenerate(levelNumber).toMap();
  }

  /// Returns a strongly typed puzzle object.
  ///
  /// A defensive copy is returned.
  Puzzle getPuzzle(int levelNumber) {
    _validateLevel(levelNumber);

    return _getOrGenerate(levelNumber).toPuzzle();
  }

  /// Background-isolate variant of [getPuzzleForLevel].
  ///
  /// Produces exactly the same puzzle, without blocking the UI isolate.
  Future<Map<String, dynamic>?> getPuzzleForLevelAsync(int levelNumber) async {
    if (levelNumber < _minimumLevel) {
      return null;
    }

    final _PuzzleData data = await _getOrGenerateAsync(levelNumber);

    return data.toMap();
  }

  /// Background-isolate variant of [getPuzzle].
  Future<Puzzle> getPuzzleAsync(int levelNumber) async {
    _validateLevel(levelNumber);

    final _PuzzleData data = await _getOrGenerateAsync(levelNumber);

    return data.toPuzzle();
  }

  /// Returns true when [levelNumber] is currently cached.
  bool isCached(int levelNumber) {
    if (levelNumber < _minimumLevel) {
      return false;
    }

    return _cache.containsKey(levelNumber);
  }

  /// Number of puzzles currently stored in the in-memory cache.
  int get cacheSize => _cache.length;

  /// Removes one puzzle from the cache.
  ///
  /// Returns true when a cached puzzle existed.
  bool removeCachedPuzzle(int levelNumber) {
    return _cache.remove(levelNumber) != null;
  }

  /// Clears every cached puzzle.
  ///
  /// This does not affect deterministic generation.
  void clearCache() {
    _cache.clear();
  }

  /// Returns the configured difficulty for [levelNumber].
  ///
  /// This is based only on the level number and never on player progress.
  PuzzleDifficulty getDifficulty(int levelNumber) {
    _validateLevel(levelNumber);

    return _PuzzleGenerator.difficultyFor(levelNumber);
  }

  /// Returns the configured number of empty cells for [levelNumber].
  int getEmptyCellCount(int levelNumber) {
    _validateLevel(levelNumber);

    return _PuzzleGenerator.emptyCellsFor(levelNumber);
  }

  // ==========================================================================
  // CACHE-AWARE GENERATION
  // ==========================================================================

  _PuzzleData _getOrGenerate(int levelNumber) {
    final _PuzzleData? cached = _cache[levelNumber];

    if (cached != null) {
      return cached;
    }

    final _PuzzleData generated = _PuzzleGenerator.generate(levelNumber);

    _cache[levelNumber] = generated;

    return generated;
  }

  Future<_PuzzleData> _getOrGenerateAsync(int levelNumber) {
    final _PuzzleData? cached = _cache[levelNumber];

    if (cached != null) {
      return Future<_PuzzleData>.value(cached);
    }

    return _pending[levelNumber] ??= _generateInBackground(levelNumber)
        .whenComplete(() {
          _pending.remove(levelNumber);
        });
  }

  Future<_PuzzleData> _generateInBackground(int levelNumber) async {
    _PuzzleData data;

    try {
      data = await _generateInIsolate(levelNumber);
    } on UnsupportedError {
      // Platforms without isolate support (for example web).
      data = _PuzzleGenerator.generate(levelNumber);
    }

    _cache[levelNumber] = data;

    return data;
  }

  /// Static so the isolate closure captures only [levelNumber], never `this`.
  static Future<_PuzzleData> _generateInIsolate(int levelNumber) {
    return Isolate.run(() => _PuzzleGenerator.generate(levelNumber));
  }

  // ==========================================================================
  // VALIDATION
  // ==========================================================================

  static const int _minimumLevel = 1;

  void _validateLevel(int levelNumber) {
    if (levelNumber < _minimumLevel) {
      throw ArgumentError.value(
        levelNumber,
        'levelNumber',
        'Level number must be at least $_minimumLevel.',
      );
    }
  }
}


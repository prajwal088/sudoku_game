/// Difficulty category assigned to a generated puzzle.
enum PuzzleDifficulty { easy, medium, hard, expert }

// ============================================================================
// BOARD CONSTANTS AND LOOKUP TABLES
// ============================================================================

const int _gridSize = 9;
const int _boxSize = 3;
const int _cellCount = _gridSize * _gridSize;

const int _minimumValue = 1;
const int _maximumValue = 9;

/// Bits 1..9 set: every legal Sudoku value.
const int _allValuesMask = 0x3FE;

/// Row / column / 3x3-box index for each of the 81 cells.
final Uint8List _rowOfCell = Uint8List.fromList(
  List<int>.generate(_cellCount, (int i) => i ~/ _gridSize),
);

final Uint8List _colOfCell = Uint8List.fromList(
  List<int>.generate(_cellCount, (int i) => i % _gridSize),
);

final Uint8List _boxOfCell = Uint8List.fromList(
  List<int>.generate(
    _cellCount,
    (int i) => ((i ~/ _gridSize) ~/ _boxSize) * _boxSize +
        ((i % _gridSize) ~/ _boxSize),
  ),
);

/// Number of set bits for every 10-bit mask.
final Uint8List _bitCount = _buildBitCountTable();

Uint8List _buildBitCountTable() {
  final Uint8List table = Uint8List(1 << (_maximumValue + 1));

  for (int mask = 1; mask < table.length; mask++) {
    table[mask] = table[mask >> 1] + (mask & 1);
  }

  return table;
}

// ============================================================================
// SEARCH STATE (bitmask-based Sudoku board)
// ============================================================================

/// Mutable 9x9 board with per-row/column/box bitmasks of used values.
///
/// Candidate lookup is O(1) instead of scanning 27 peer cells, which is what
/// makes generation and uniqueness checks fast. Behaviour is equivalent to a
/// plain "is this value safe here" scan.
class _SearchState {
  final Uint8List cells = Uint8List(_cellCount);

  final Uint16List _rows = Uint16List(_gridSize);
  final Uint16List _cols = Uint16List(_gridSize);
  final Uint16List _boxes = Uint16List(_gridSize);

  _SearchState.empty();

  _SearchState.fromCells(Uint8List source) {
    for (int index = 0; index < _cellCount; index++) {
      final int value = source[index];

      if (value != 0) {
        place(index, value);
      }
    }
  }

  void place(int index, int value) {
    final int bit = 1 << value;

    cells[index] = value;
    _rows[_rowOfCell[index]] |= bit;
    _cols[_colOfCell[index]] |= bit;
    _boxes[_boxOfCell[index]] |= bit;
  }

  void clear(int index) {
    final int bit = 1 << cells[index];

    cells[index] = 0;
    _rows[_rowOfCell[index]] &= ~bit;
    _cols[_colOfCell[index]] &= ~bit;
    _boxes[_boxOfCell[index]] &= ~bit;
  }

  /// Bitmask of values that can legally be placed in [index].
  int candidateMask(int index) {
    return ~(_rows[_rowOfCell[index]] |
            _cols[_colOfCell[index]] |
            _boxes[_boxOfCell[index]]) &
        _allValuesMask;
  }

  /// Finds the empty cell with the fewest legal candidates.
  ///
  /// Returns -1 when the board has no empty cell.
  ///
  /// Tie-breaking and early exits are part of the determinism contract:
  /// the FIRST cell (row-major) with the lowest count wins, and the search
  /// stops immediately at the first cell with 0 or 1 candidates.
  int findBestEmptyCell() {
    int bestIndex = -1;
    int bestCount = _maximumValue + 1;

    for (int index = 0; index < _cellCount; index++) {
      if (cells[index] != 0) {
        continue;
      }

      final int count = _bitCount[candidateMask(index)];

      if (count < bestCount) {
        bestCount = count;
        bestIndex = index;

        if (count <= 1) {
          return bestIndex;
        }
      }
    }

    return bestIndex;
  }

  /// Randomized backtracking fill used to generate a complete board.
  ///
  /// Determinism contract: for every visited node a fresh [1..9] list is
  /// shuffled with [random] BEFORE candidates are filtered.
  bool fill(Random random) {
    final int index = findBestEmptyCell();

    if (index < 0) {
      return true;
    }

    final int mask = candidateMask(index);

    final List<int> order = <int>[
      for (int value = _minimumValue; value <= _maximumValue; value++) value,
    ];

    order.shuffle(random);

    for (final int value in order) {
      if ((mask & (1 << value)) == 0) {
        continue;
      }

      place(index, value);

      if (fill(random)) {
        return true;
      }

      clear(index);
    }

    return false;
  }

  /// Counts solutions, stopping once [limit] is reached.
  ///
  /// The result never exceeds [limit]. The board is restored before returning.
  int countSolutions(int limit) {
    final int index = findBestEmptyCell();

    if (index < 0) {
      return 1;
    }

    int remaining = candidateMask(index);
    int count = 0;

    while (remaining != 0 && count < limit) {
      final int bit = remaining & -remaining;

      remaining ^= bit;

      place(index, bit.bitLength - 1);

      count += countSolutions(limit - count);

      clear(index);
    }

    return count;
  }
}

// ============================================================================
// PUZZLE GENERATOR
// ============================================================================

/// Pure, stateless puzzle generation.
///
/// Kept free of repository state so it can run inside a background isolate.
abstract final class _PuzzleGenerator {
  // --------------------------------------------------------------------------
  // DIFFICULTY CONFIGURATION
  // --------------------------------------------------------------------------

  static const int _easyMaximumLevel = 25;
  static const int _mediumMaximumLevel = 75;
  static const int _hardMaximumLevel = 150;

  /// Number of empty cells for each difficulty.
  ///
  /// These values control generation difficulty.
  /// They do not guarantee a particular human-solving difficulty.
  static const int _easyEmptyCells = 35;
  static const int _mediumEmptyCells = 45;
  static const int _hardEmptyCells = 55;
  static const int _expertEmptyCells = 57;

  // --------------------------------------------------------------------------
  // GENERATION LIMITS
  // --------------------------------------------------------------------------

  /// Maximum deterministic retries for one level.
  static const int _maximumGenerationAttempts = 10;

  /// The uniqueness checker only needs to distinguish:
  /// - 0 solutions
  /// - 1 solution
  /// - 2+ solutions
  static const int _solutionCountLimit = 2;

  // --------------------------------------------------------------------------
  // DIFFICULTY
  // --------------------------------------------------------------------------

  static PuzzleDifficulty difficultyFor(int levelNumber) {
    if (levelNumber <= _easyMaximumLevel) {
      return PuzzleDifficulty.easy;
    }

    if (levelNumber <= _mediumMaximumLevel) {
      return PuzzleDifficulty.medium;
    }

    if (levelNumber <= _hardMaximumLevel) {
      return PuzzleDifficulty.hard;
    }

    return PuzzleDifficulty.expert;
  }

  static int emptyCellsFor(int levelNumber) {
    if (levelNumber <= _easyMaximumLevel) {
      return _easyEmptyCells;
    }

    if (levelNumber <= _mediumMaximumLevel) {
      return _mediumEmptyCells;
    }

    if (levelNumber <= _hardMaximumLevel) {
      return _hardEmptyCells;
    }

    return _expertEmptyCells;
  }

  // --------------------------------------------------------------------------
  // GENERATION
  // --------------------------------------------------------------------------

  static _PuzzleData generate(int levelNumber) {
    final int emptyCells = emptyCellsFor(levelNumber);

    for (int attempt = 0; attempt < _maximumGenerationAttempts; attempt++) {
      final Random random = Random(_createSeed(levelNumber, attempt));

      final Uint8List solution = _generateSolvedCells(random);

      final Uint8List? puzzle = _createUniquePuzzle(
        solution: solution,
        emptyCells: emptyCells,
        random: random,
      );

      if (puzzle == null) {
        continue;
      }

      _validateSolvedCells(solution);
      _validatePuzzleCells(puzzle, solution);

      return _PuzzleData(
        puzzle: _toGrid(puzzle),
        solution: _toGrid(solution),
        difficulty: difficultyFor(levelNumber),
      );
    }

    throw StateError(
      'Unable to generate a unique Sudoku puzzle for level '
      '$levelNumber after $_maximumGenerationAttempts attempts.',
    );
  }

  /// Creates a deterministic seed from the level and generation attempt.
  ///
  /// The attempt value allows deterministic retries while preserving the
  /// same output for a given level. Do not change these constants.
  static int _createSeed(int levelNumber, int attempt) {
    const int levelMultiplier = 1000003;
    const int attemptMultiplier = 7919;

    return ((levelNumber * levelMultiplier) + (attempt * attemptMultiplier)) &
        0x7fffffff;
  }

  /// Generates a complete valid Sudoku solution using randomized
  /// backtracking.
  static Uint8List _generateSolvedCells(Random random) {
    final _SearchState state = _SearchState.empty();

    if (!state.fill(random)) {
      throw StateError('Failed to generate a valid Sudoku solution.');
    }

    return state.cells;
  }

  /// Removes clues while preserving exactly one solution.
  ///
  /// Returns null when the requested number of empty cells cannot be reached.
  static Uint8List? _createUniquePuzzle({
    required Uint8List solution,
    required int emptyCells,
    required Random random,
  }) {
    if (emptyCells < 0 || emptyCells >= _cellCount) {
      throw ArgumentError.value(
        emptyCells,
        'emptyCells',
        'Empty cells must be between 0 and ${_cellCount - 1}.',
      );
    }

    final _SearchState state = _SearchState.fromCells(solution);

    if (emptyCells == 0) {
      return state.cells;
    }

    final List<int> positions = <int>[
      for (int index = 0; index < _cellCount; index++) index,
    ];

    positions.shuffle(random);

    int removed = 0;

    for (final int index in positions) {
      if (removed >= emptyCells) {
        break;
      }

      final int previousValue = state.cells[index];

      if (previousValue == 0) {
        continue;
      }

      state.clear(index);

      if (state.countSolutions(_solutionCountLimit) == 1) {
        removed++;
      } else {
        state.place(index, previousValue);
      }
    }

    if (removed != emptyCells) {
      return null;
    }

    return state.cells;
  }

  // --------------------------------------------------------------------------
  // VALIDATION
  // --------------------------------------------------------------------------

  /// Validates that cells form a complete valid Sudoku solution.
  static void _validateSolvedCells(Uint8List cells) {
    final List<int> rows = List<int>.filled(_gridSize, 0);
    final List<int> cols = List<int>.filled(_gridSize, 0);
    final List<int> boxes = List<int>.filled(_gridSize, 0);

    for (int index = 0; index < _cellCount; index++) {
      final int row = _rowOfCell[index];
      final int col = _colOfCell[index];
      final int box = _boxOfCell[index];
      final int value = cells[index];

      if (value < _minimumValue || value > _maximumValue) {
        throw StateError(
          'Generated solution contains invalid value '
          '$value at ($row, $col).',
        );
      }

      final int bit = 1 << value;

      if ((rows[row] & bit) != 0) {
        throw StateError(
          'Generated solution contains duplicate values in row $row.',
        );
      }

      if ((cols[col] & bit) != 0) {
        throw StateError(
          'Generated solution contains duplicate values in column $col.',
        );
      }

      if ((boxes[box] & bit) != 0) {
        throw StateError(
          'Generated solution contains duplicate values '
          'in box (${(box ~/ _boxSize) * _boxSize}, '
          '${(box % _boxSize) * _boxSize}).',
        );
      }

      rows[row] |= bit;
      cols[col] |= bit;
      boxes[box] |= bit;
    }
  }

  /// Validates a playable puzzle against its solution.
  ///
  /// The expensive uniqueness re-check only runs in debug/profile builds
  /// (asserts enabled): uniqueness is already guaranteed by construction,
  /// because every accepted clue removal was verified to leave exactly one
  /// solution.
  static void _validatePuzzleCells(Uint8List puzzle, Uint8List solution) {
    final List<int> rows = List<int>.filled(_gridSize, 0);
    final List<int> cols = List<int>.filled(_gridSize, 0);
    final List<int> boxes = List<int>.filled(_gridSize, 0);

    for (int index = 0; index < _cellCount; index++) {
      final int row = _rowOfCell[index];
      final int col = _colOfCell[index];
      final int box = _boxOfCell[index];
      final int value = puzzle[index];

      if (value > _maximumValue) {
        throw StateError(
          'Generated puzzle contains invalid value $value at ($row, $col).',
        );
      }

      if (value == 0) {
        continue;
      }

      final int bit = 1 << value;

      if ((rows[row] & bit) != 0 ||
          (cols[col] & bit) != 0 ||
          (boxes[box] & bit) != 0) {
        throw StateError(
          'Generated puzzle contains an invalid Sudoku conflict '
          'at ($row, $col).',
        );
      }

      if (value != solution[index]) {
        throw StateError(
          'Generated puzzle clue at ($row, $col) does not match the '
          'solution.',
        );
      }

      rows[row] |= bit;
      cols[col] |= bit;
      boxes[box] |= bit;
    }

    assert(() {
      final int solutionCount = _SearchState.fromCells(
        puzzle,
      ).countSolutions(_solutionCountLimit);

      if (solutionCount != 1) {
        throw StateError(
          'Generated puzzle does not have exactly one solution.',
        );
      }

      return true;
    }());
  }

  // --------------------------------------------------------------------------
  // CONVERSION
  // --------------------------------------------------------------------------

  static List<List<int>> _toGrid(Uint8List cells) {
    return List<List<int>>.generate(
      _gridSize,
      (int row) => List<int>.generate(
        _gridSize,
        (int col) => cells[(row * _gridSize) + col],
        growable: false,
      ),
      growable: false,
    );
  }
}

// ============================================================================
// GRID COPY
// ============================================================================

List<List<int>> _cloneGrid(List<List<int>> source) {
  return List<List<int>>.generate(
    source.length,
    (int row) => List<int>.from(source[row], growable: false),
    growable: false,
  );
}

